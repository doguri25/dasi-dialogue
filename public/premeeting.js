// 학생마다 안내 → 경험 듣기 순서를 따로 유지합니다.
export function preStepFor(session,target=session.target) {
 if(['intro','story'].includes(session.preSteps?.[target]))return session.preSteps[target];
 // 이전 기록은 이미 대화한 상대의 이야기를 계속 듣습니다.
 return session.messages.some(m=>m.phase==='pre'&&m.kind==='teacher'&&m.target===target)?'story':'intro';
}
export function markIntroductionSent(session,target=session.target) {
 session.preSteps={...session.preSteps,[target]:'story'};
}
