import {preStepFor,introductionOptions} from './premeeting.js';
import {followupOptions} from './followups.js';
// 진행자가 골라 발문하는 창작 예시. 정답 채점이나 학생의 동의를 대신하지 않습니다.
export function questionOptions(session,scenario) {
 const {phase,target,variant}=session;
 const guardian=target==='g',actor=target==='a',victim=target==='v';
 const child=guardian?'학생은':'너는';
 let rows;
 if(phase==='pre'&&preStepFor(session)==='intro')return introductionOptions(target).map(([label,text],i)=>({id:`pre-intro-${target}-${variant}-${i}`,label,text}));
 if(phase==='pre') rows=guardian?[
  ['들은 이야기','어떤 일이 있었다고 학생에게 들으셨나요? 기억하시는 대로 말씀해 주세요.'],
  ['처음 알게 된 때','그 일을 처음 알게 되셨을 때 어떤 이야기를 들으셨나요?'],
  ['직접 본 모습','직접 보신 상황과 학생에게 들은 이야기를 나누어 말씀해 주시겠어요?'],
  ['학생의 반응','학생은 그 일을 이야기하면서 어떤 마음을 표현했나요?'],
  ['이야기 이어가기','그 뒤에는 어떤 일이 이어졌나요?'],
  ['더 듣고 싶은 점','제가 아직 듣지 못한 이야기나 더 말씀하고 싶은 부분이 있을까요?'],
  ['생활의 변화','그 일이 있은 뒤 학생의 일상에서 무엇이 달라졌나요?'],
  ['이해 확인','제가 들은 내용을 다시 짚어 보겠습니다. 빠뜨리거나 다르게 이해한 부분이 있을까요?']
 ]:[
  ['무슨 일이 있었니?','무슨 일이 있었는지 네가 기억하는 대로 이야기해 줄래?'],
  ['처음부터 천천히','그 일이 시작되기 전부터 차근차근 들려줄래?'],
  ['네가 겪은 장면','그때 네가 보고 들은 일은 무엇이었니? 말하고 싶은 장면부터 이야기해 줘.'],
  ['그때의 마음','그 일이 일어났을 때 어떤 생각이 들었고 어떤 마음이었니?'],
  ['그다음 이야기','그다음에는 어떤 일이 이어졌니? 천천히 들어 볼게.'],
  ['더 하고 싶은 말','선생님이 아직 듣지 못한 이야기나 꼭 말하고 싶은 것이 있니?'],
  ['일상의 변화','그 일이 있은 뒤 학교생활에서 무엇이 달라졌니?'],
  ['이해 확인','네 이야기를 선생님이 제대로 들었는지 확인하고 싶어. 빠뜨리거나 다르게 이해한 부분이 있니?']
 ];
 else if(phase==='main') rows=[
  ['대화 약속',guardian?'학생들이 안전하게 이야기하도록 어른들은 어떤 대화 약속을 지키면 좋을까요?':'서로의 이야기를 듣는 동안 어떤 약속이 있으면 좋을까?'],
  ['경험 듣기',guardian?'학생의 이야기를 듣고 더 이해하게 된 점은 무엇인가요?':'다른 사람의 이야기를 듣고 새롭게 알게 된 점은 무엇이니?'],
  ['영향 살피기',guardian?'이번 일로 학생의 일상에 어떤 영향이 있었다고 이해하셨나요?':victim?'그 일이 너의 일상에 어떤 영향을 주었는지 말해 줄래?':'그 행동이 상대의 생활에 어떤 영향을 주었을까?'],
  ['필요 확인',guardian?'학생이 바라는 변화를 돕기 위해 어떤 지원이 필요할까요?':`이 상황에서 ${child} 무엇이 달라지기를 바라니?`],
  [victim?'회복 방식':'책임 행동',guardian?'학생 대신 결정하지 않으면서 보호자로서 실천할 수 있는 일은 무엇일까요?':victim?'제안된 회복 방법 중 받아들일 수 있는 것과 원하지 않는 것은 무엇이니?':'피해를 줄이고 회복을 돕기 위해 스스로 실천할 수 있는 행동은 무엇일까?'],
  ['구체적 계획',guardian?'어른이 도울 일은 누가 언제부터 어떻게 실천하면 좋을까요?':'각자가 동의한 행동을 누가 언제부터 어떻게 실천하면 좋을까?'],
  ['동의 다시 확인',guardian?'학생들이 이 약속에 자유롭게 동의했는지 어떻게 확인하면 좋을까요?':'이 제안에 동의하지 않는 부분이나 바꾸고 싶은 부분이 있니? 거절해도 괜찮아.'],
  ['점검 계획',guardian?'약속이 지켜지는지 학생에게 부담을 넘기지 않고 어떻게 확인하면 좋을까요?':'약속이 지켜지는지 누가 언제 확인하고, 어려우면 누구에게 도움을 요청할까?']
 ];
 else rows=[
  ['실천 확인',guardian?'약속 뒤 실제로 달라진 행동을 관찰하신 것이 있나요?':'약속 중 실제로 지켜진 것은 무엇이니? 구체적인 장면을 말해 줄래?'],
  ['변화 확인',guardian?'학생은 이전보다 무엇이 나아졌다고 이야기하나요?':'그 변화가 네 일상에는 어떤 차이를 만들었니?'],
  ['현재 안전',guardian?'학생에게 다시 불편하거나 두려운 일이 있었는지 따로 확인하셨나요?':'다시 불편하거나 두려웠던 일이 있었니? 지금도 안전하게 느끼는지 알고 싶어.'],
  ['어려움 확인',guardian?'약속을 실천하는 과정에서 어른의 지원이 부족했던 부분은 무엇인가요?':victim?'아직 바뀌지 않아서 힘든 점은 무엇이니? 네가 혼자 확인할 책임은 없어.':'약속을 지키기 어려웠던 순간에는 어떤 일이 있었니?'],
  ['다시 회복하기',guardian?'약속이 지켜지지 않은 부분에 대해 어른이 먼저 해야 할 일은 무엇일까요?':victim?'약속이 지켜지지 않았다면 지금 어떤 보호와 회복이 필요하니?':'약속이 지켜지지 않은 부분을 인정하고 다시 책임질 행동은 무엇이니?'],
  ['추가 지원',guardian?'학생이 원하는 지원과 어른이 더 도울 일은 무엇일까요?':'지금 어른이 더 도와줄 일은 무엇일까?'],
  ['다음 점검',guardian?'누가 언제 학생을 따로 만나 변화와 안전을 다시 확인하면 좋을까요?':'다음에는 누가 언제 만나서 변화와 안전을 다시 확인하면 좋을까?'],
  ['이후 선택',guardian?'학생이 추가 모임을 원하는지, 개별 지원을 원하는지 어떻게 확인할까요?':'앞으로 함께 만나고 싶은지, 따로 도움받고 싶은지 네 생각을 들려줄래?']
 ];
 if(variant==='unsafe')rows.splice(0,4,...(guardian?[
  ['거절 존중','학생이 만나고 싶지 않다는 뜻을 존중하면서 지금 필요한 보호를 어떻게 마련할까요?'],
  ['안전 확인','학생이 두려워하는 상황과 지금 당장 필요한 지원은 무엇인가요?'],
  ['대면 보류','함께 만나는 일은 중단하고, 학생을 개별로 지원하는 방법을 이야기해도 괜찮을까요?'],
  ['지원 연결','학교에서 학생의 안전을 확인하고 도울 어른을 어떻게 정하면 좋을까요?']
 ]:actor?[
  ['거절 존중','상대가 만나기를 원하지 않을 때 그 선택을 존중하려면 어떻게 해야 할까?'],
  ['접촉 중단','상대가 원하지 않는 접촉을 멈추기 위해 어떤 행동을 할 수 있니?'],
  ['대면 보류','오늘은 함께 만나는 일을 중단하고 따로 이야기하려 해. 어떤 도움이 필요하니?'],
  ['책임과 지원','상대를 찾아가지 않고 네 마음을 정리하려면 어떤 어른의 도움이 필요할까?']
 ]:[
  ['거절 존중','만나고 싶지 않다는 네 뜻을 존중해. 오늘은 중단하고 따로 이야기해도 괜찮니?'],
  ['겪은 일 듣기','말하고 싶다면, 어떤 일이 불편했는지 들려줄래? 말하기 어려운 것은 넘어가도 돼.'],
  ['지원 선택','함께 만나지 않더라도 받을 수 있는 도움 중 네가 원하는 것은 무엇이니?'],
  ['도움 요청','다시 불편한 일이 생기면 곧바로 도움을 요청할 수 있는 어른은 누구일까?']
 ]));
 if(variant==='resistant'&&phase!=='post')rows[1]=['이야기 기다리기',guardian?'이 대화에서 아직 충분히 들리지 않았다고 느끼는 이야기가 있으신가요?':'말하기 어렵거나 충분히 듣지 않았다고 느끼는 부분이 있니? 기다릴게.'];
 if(variant==='relapse'&&phase==='post')rows[0]=['미이행 확인',guardian?'약속이 다시 지켜지지 않았을 때 학생은 어떤 일을 겪었다고 말했나요?':'약속이 다시 지켜지지 않은 부분은 무엇이니? 실제 있었던 일을 하나씩 살펴보자.'];
 const general=rows.map(([label,text],i)=>({id:`${phase}-${phase==='pre'?'story-':''}${target}-${variant}-${i}`,label,text}));
 const followups=followupOptions(session,scenario);
 return followups.length?[...followups,...general.filter(q=>!followups.some(f=>f.text===q.text)).slice(0,4)]:general;
}
